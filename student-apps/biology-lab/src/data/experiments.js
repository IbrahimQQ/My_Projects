export const getAllExperiments = () => {
  const experiments = [];
  Object.entries(biologyExperiments).forEach(([categoryId, category]) => {
    category.experiments.forEach(exp => {
      experiments.push({ ...exp, categoryId, categoryTitle: category.title, categoryIcon: category.icon, categoryColor: category.color });
    });
  });
  return experiments;
};

export const getTotalExperiments = () => Object.values(biologyExperiments).reduce((sum, cat) => sum + cat.experiments.length, 0);
