// Helper function to get all experiments as flat list
export const getAllExperiments = () => {
  const experiments = [];
  Object.entries(chemistryExperiments).forEach(([categoryId, category]) => {
    category.experiments.forEach(exp => {
      experiments.push({
        ...exp,
        categoryId,
        categoryTitle: category.title,
        categoryIcon: category.icon,
        categoryColor: category.color,
      });
    });
  });
  return experiments;
};

// Get total number of experiments
export const getTotalExperiments = () => {
  return Object.values(chemistryExperiments).reduce(
    (sum, category) => sum + category.experiments.length,
    0
  );
};
